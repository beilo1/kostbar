def schema_status(db):
    relation = db.execute("SELECT to_regclass('schema_migrations') AS relation").fetchone()["relation"]
    if relation is None:
        return []
    return [dict(row) for row in db.execute(
        "SELECT version,name,checksum,applied_at FROM schema_migrations ORDER BY version"
    )]


def validate_baseline(db):
    rows = db.execute("""SELECT table_name,column_name,udt_name FROM information_schema.columns
                         WHERE table_schema=current_schema() AND table_name=ANY(%s)""",
                      (list(BASELINE_COLUMNS),))
    actual = {}
    for row in rows:
        actual.setdefault(row["table_name"], {})[row["column_name"]] = row["udt_name"]
    incompatible = [f"{table}.{column} ({kind})"
                    for table, columns in BASELINE_COLUMNS.items()
                    for column, kind in columns.items()
                    if actual.get(table, {}).get(column) != kind]
    if incompatible:
        raise MigrationError("Das unversionierte Schema entspricht nicht dem v35-Schema. Fehlende oder anders typisierte Spalten: "
                             + ", ".join(incompatible)
                             + ". Eine leere Datenbank für v35 verwenden.")


def migrate(db, plan=MIGRATIONS):
    """Caller owns the transaction; PostgreSQL rolls back DDL and records together."""
    if getattr(db, "autocommit", False) is True:
        raise MigrationError("Migrationen benötigen eine gemeinsame Datenbanktransaktion.")
    if (not plan or [m.version for m in plan] != list(range(1, len(plan) + 1))
            or any(not m.name or not m.sql.strip() for m in plan)):
        raise MigrationError("Migrationsplan muss lueckenlos bei Version 1 beginnen.")
    db.execute("SET LOCAL lock_timeout='15s'")
    db.execute("SET LOCAL statement_timeout='60s'")
    db.execute("SELECT pg_advisory_xact_lock(739310481)")
    db.execute("""CREATE TABLE IF NOT EXISTS schema_migrations (
                    version INTEGER PRIMARY KEY, name TEXT NOT NULL, checksum TEXT NOT NULL,
                    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)""")
    applied = schema_status(db)
    versions = [row["version"] for row in applied]
    if versions != list(range(1, len(versions) + 1)) or len(applied) > len(plan):
        raise MigrationError("Datenbankschema ist neuer als die Anwendung oder die Migrationshistorie ist unvollstaendig.")
    for recorded, expected in zip(applied, plan):
        if (recorded["name"], recorded["checksum"]) != (expected.name, expected.checksum):
            raise MigrationError(f"Pruefsumme oder Name der bereits angewendeten Migration {expected.version} stimmt nicht.")
    for migration in plan[len(applied):]:
        db.execute(migration.sql, prepare=False)
        if migration.version == 1:
            validate_baseline(db)
        db.execute("INSERT INTO schema_migrations (version,name,checksum) VALUES (%s,%s,%s)",
                   (migration.version, migration.name, migration.checksum))
    return plan[-1].version
