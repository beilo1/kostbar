class MigrationError(RuntimeError):
    """Refuse unsupported or inconsistent schemas before serving requests."""


@dataclass(frozen=True)
class Migration:
    version: int
    name: str
    sql: str

    @property
    def checksum(self):
        return hashlib.sha256(self.sql.encode("utf-8")).hexdigest()


